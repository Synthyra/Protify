"""The probe matrix's inputs: a base's canonical store, or a generated control, read as pooled branches.

A cell names what its head reads as branch specs, such as `ESMC-300-SAE-l23-k64-c16384:max`, `ESMC-300:mean,var`,
`ESMC-300:mean` or `Random:mean`. This module maps each spec to one pooled stream of a canonical view and cuts the
columns the spec asks for:

| branch spec                      | stream          | columns read                      | width |
|----------------------------------|-----------------|-----------------------------------|-------|
| `<base>-SAE-...:max`             | `sae_max`       | all                               | c     |
| `<base>:mean,var`                | `final_mean_var`| all (mean, then variance)         | 2d    |
| `<base>:mean`                    | `final_mean_var`| the first half, the mean          | d     |
| `Random:mean`, `OneHot-Protein:mean` | `final_mean_var` of the control | the first half         | d / v |
| `Atlas-Profile:profile`          | `profile` of the cell's `profile_root` | all (one probability per axis protein) | p |

Every stream pools all l + 2 token rows (CLS, l residues, EOS), so a mean here is the mean the engine stored. A
stored base is read with `foundry.embedding.open_canonical_view`; a control is never stored and is generated by
`SyntheticControlView` where it is read. Both views are `FeatureView`-shaped, so `IndexedBranchEmbeddings` joins them
and the declared-dataset training loop reads them as it reads any native input.

The cell setting is a plain mapping, `probe_features_record(...)`. It pins no file digest: the engine verifies each
part it reads, and `probe_provenance` records which store and streams a package read.

The Atlas profile is not a stream of a base's canonical store, so a cell that reads it names a second root, `profile_root`
(`data/atlas_profile_feature.py`), beside the base's. It rides with at least one canonical stream, and its sequences are
checked against the store before any training starts.

Shapes: `b` rows requested, `c` SAE codebook (16384), `d` hidden width of the base, `p` proteins of the profile's axis
(about 20,000), `w` columns of one branch.
"""

from __future__ import annotations

import numpy as np
import torch

from collections.abc import Iterable, Mapping, Sequence
from concurrent.futures import ProcessPoolExecutor
from itertools import repeat
from multiprocessing import get_context
from pathlib import Path
from types import SimpleNamespace
from typing import Any
from tqdm.auto import tqdm

from foundry.embedding import (
    ONE_HOT,
    RANDOM_VECTOR,
    ReadBudget,
    SyntheticControlView,
    open_canonical_view,
    sequence_inventory,
)
from foundry.embedding.canonical import FINAL_MEAN_VAR, SAE_MAX, read_manifest
from foundry.embedding.contracts import normalize_sequence
from .atlas_profile_feature import AtlasProfileFeature, profile_provenance
from .branch_features import BranchSpec, IndexedBranchEmbeddings, parse_branch_spec
from ..base_models.esmc_sae import parse_sae_model_name


SCHEMA = "probe_features_v1"
STORED = "stored"
GENERATED = "generated"
CONTROLS = (RANDOM_VECTOR, ONE_HOT)
FIELDS = frozenset({"schema", "base", "kind", "root", "control"})
# Only a cell that reads the Atlas profile carries `profile_root`, so every other cell's record is the one it always was.
PROFILE_ROOT = "profile_root"
PROFILE_FIELDS = FIELDS | {PROFILE_ROOT}
# The stream name of the profile branch beside the canonical store's `sae_max` and `final_mean_var`; the store holds none of its own.
PROFILE_STREAM = "atlas_profile"
# What the reader returns at once: a stored store's rows are small, a control builds every requested protein's token rows.
STORED_BUDGET = ReadBudget(max_rows=256, max_padded_residues=32768, max_bytes=256 * 1024 * 1024)
GENERATED_BUDGET = ReadBudget(max_rows=64, max_padded_residues=32768, max_bytes=256 * 1024 * 1024)
# The cut of a stream a branch reads: all columns, or the mean half of `final_mean_var`.
WHOLE, MEAN_HALF = "whole", "mean_half"


# A control's rows are made once per cell, here, and held in memory: the reader would otherwise rebuild every protein's token
# rows on every batch of every epoch (about 12 s per 1,000 proteins for the random control). Nothing is written to disk. Fewer
# than PARALLEL_FROM proteins are made in this process, and more by CONTROL_WORKERS processes of one thread each.
CONTROL_WORKERS = 6
PARALLEL_FROM = 4096


def _pooled_chunk(kind: str, texts: list[str]) -> np.ndarray:
    """The pooled rows of one chunk of proteins, float32 `(b, 2w)`, made by a worker that holds one thread."""
    torch.set_num_threads(1)
    view = SyntheticControlView(kind, sequence_inventory(texts), budget=GENERATED_BUDGET)
    return view.pooled(texts).numpy()  # (b, 2w)


class MaterializedControl:
    """`SyntheticControlView`'s pooled surface over rows already made for every protein of a cell.

    A generated control is a deterministic function of the sequence, so these rows are the ones the view makes where it is read.
    """

    def __init__(self, view: SyntheticControlView, workers: int = CONTROL_WORKERS) -> None:
        self.view = view
        self.budget = view.budget
        texts = list(view.sequences)
        chunks = [texts[start:start + GENERATED_BUDGET.max_rows] for start in range(0, len(texts), GENERATED_BUDGET.max_rows)]
        progress = tqdm(total=len(chunks), desc=f"control rows ({view.kind})", mininterval=30, smoothing=0)
        blocks: list[np.ndarray] = []  # chunks of (b_j, 2w), in order
        if len(texts) < PARALLEL_FROM or workers < 2:
            made: Iterable[np.ndarray] = map(_pooled_chunk, repeat(view.kind), chunks)
            for block in made:
                blocks.append(block)
                progress.update(1)
        else:
            with ProcessPoolExecutor(max_workers=workers, mp_context=get_context("spawn")) as pool:
                for block in pool.map(_pooled_chunk, repeat(view.kind), chunks):
                    blocks.append(block)
                    progress.update(1)
        progress.close()
        self.rows = torch.from_numpy(np.concatenate(blocks)) if blocks else torch.empty((0, 2 * view.width))  # (n, 2w)
        self.index = {text: row for row, text in enumerate(texts)}

    @property
    def sequences(self) -> tuple[str, ...]:
        return self.view.sequences

    def descriptor(self, name: str) -> Any:
        return self.view.descriptor(name)

    def pooled(self, sequences: Sequence[str], names: Sequence[str] | None = None) -> torch.Tensor:
        """Mean then variance over all l + 2 rows, float32 `(b, 2w)`."""
        if names is not None and tuple(names) != (FINAL_MEAN_VAR,):
            raise ValueError(f"A control pools only {FINAL_MEAN_VAR!r}; received {tuple(names)}.")
        return self.rows[[self.index[normalize_sequence(sequence)] for sequence in sequences]]  # (b, 2w)

    def close(self) -> None:
        self.view.close()


def probe_features_record(
    base: str, *, root: str | Path | None = None, control: str | None = None, profile_root: str | Path | None = None,
) -> dict[str, Any]:
    """The cell setting for a stored base (its store root) or a generated control (its engine kind).

    `profile_root`, for a stored base only, names the Atlas profile store a `Atlas-Profile:profile` branch reads.
    """
    record = {
        "schema": SCHEMA, "base": base, "kind": GENERATED if control is not None else STORED,
        "root": None if root is None else str(root), "control": control,
    }
    if profile_root is not None:
        record[PROFILE_ROOT] = str(profile_root)
    return validate_probe_features(record)


def validate_probe_features(record: object) -> dict[str, Any]:
    """The setting, refused unless it names exactly one source: a store root, or a control the engine generates."""
    if not isinstance(record, Mapping) or set(record) not in (FIELDS, PROFILE_FIELDS) or record["schema"] != SCHEMA:
        raise ValueError(f"probe_features is a mapping of {sorted(FIELDS)}, and {PROFILE_ROOT} when it reads the Atlas profile, with schema {SCHEMA!r}.")
    if not isinstance(record["base"], str) or not record["base"]:
        raise ValueError("probe_features.base must name the base.")
    if PROFILE_ROOT in record and (
        record["kind"] != STORED or not isinstance(record[PROFILE_ROOT], str) or not Path(record[PROFILE_ROOT]).is_absolute()
    ):
        raise ValueError(f"probe_features.{PROFILE_ROOT} is the absolute root of an Atlas profile store, and only a stored base reads one.")
    if record["kind"] == STORED:
        if record["control"] is not None or not isinstance(record["root"], str) or not Path(record["root"]).is_absolute():
            raise ValueError("a stored probe input names the absolute root of its canonical store and no control.")
    elif record["kind"] == GENERATED:
        if record["root"] is not None or record["control"] not in CONTROLS:
            raise ValueError(f"a generated probe input names a control of {CONTROLS} and no store root.")
    else:
        raise ValueError(f"probe_features.kind must be {STORED!r} or {GENERATED!r}.")
    return dict(record)


def branch_stream(spec: BranchSpec) -> tuple[str, str]:
    """The pooled stream a branch spec reads and how much of it: SAE max, the final mean and variance, or the mean alone."""
    if spec.hidden_state_index != -1:
        raise ValueError(f"{spec.slug} reads hidden state {spec.hidden_state_index}; a probe input pools the final layer only.")
    if spec.profile:
        return PROFILE_STREAM, WHOLE
    if spec.sparse:
        if spec.pooling_types != ("max",):
            raise ValueError(f"{spec.slug}: the stored SAE stream is pooled by max over all rows.")
        return SAE_MAX, WHOLE
    if spec.pooling_types == ("mean", "var"):
        return FINAL_MEAN_VAR, WHOLE
    if spec.pooling_types == ("mean",):
        return FINAL_MEAN_VAR, MEAN_HALF
    raise ValueError(f"{spec.slug}: a probe input pools the final layer as mean or as mean then var, not {spec.pooling_types}.")


class ProbeBranchView:
    """`FeatureView`'s pooled surface over the branches of a cell: one named branch per spec, each cut to the columns it asks for.

    `IndexedBranchEmbeddings` reads `sequences`, `budget`, `descriptor(name)` and `pooled(sequences, names)`, and
    this class answers all four from one engine view, so a stored base and a control read alike. A control answers
    in blocks, since it builds the token rows of every protein it is asked for. An Atlas profile branch is answered
    from `profile`, which the engine's view does not hold.
    """

    def __init__(
        self, view: Any, branches: Sequence[tuple[str, str]], block_rows: int | None, profile: AtlasProfileFeature | None = None,
    ) -> None:
        self.view = view
        self.profile = profile
        if profile is None and any(stream == PROFILE_STREAM for stream, _ in branches):
            raise ValueError("a profile branch needs the Atlas profile store it reads.")
        self.branches = {f"branch{index}": branch for index, branch in enumerate(branches)}
        self.names = tuple(self.branches)
        self.block_rows = block_rows
        self.budget = STORED_BUDGET if block_rows is None else ReadBudget(
            max_rows=1024, max_padded_residues=32768, max_bytes=STORED_BUDGET.max_bytes,
        )

    @property
    def sequences(self) -> tuple[str, ...]:
        return tuple(self.view.sequences)

    def descriptor(self, name: str) -> SimpleNamespace:
        stream, part = self.branches[name]
        if stream == PROFILE_STREAM:
            return SimpleNamespace(layout="dense", width=self.profile.width, dtype=torch.float32)  # p
        inner = self.view.descriptor(stream)
        width = inner.width // 2 if part == MEAN_HALF else inner.width  # w
        # A cut or generated column block is read dense; a whole SAE stream keeps its stored layout for the byte estimate.
        layout = inner.layout if part == WHOLE and inner.layout in {"dense", "csr"} else "dense"
        return SimpleNamespace(layout=layout, width=width, dtype=torch.float32)

    def pooled(self, sequences: Sequence[str], names: Sequence[str] | None = None) -> torch.Tensor:
        """The named branches' columns side by side, float32 `(b, sum of widths)`, in request order."""
        wanted = self.names if names is None else tuple(names)
        step = self.block_rows or max(len(sequences), 1)
        blocks = []
        for start in range(0, len(sequences), step):
            texts = list(sequences[start:start + step])
            blocks.append(torch.cat([self._branch(texts, name) for name in wanted], dim=1))  # (b_j, W)
        return torch.cat(blocks) if blocks else torch.empty((0, sum(self.descriptor(name).width for name in wanted)))  # (b, W)

    def _branch(self, texts: list[str], name: str) -> torch.Tensor:
        stream, part = self.branches[name]
        if stream == PROFILE_STREAM:
            return self.profile.read(texts)  # (b_j, p), float32
        rows = self.view.pooled(texts, (stream,))  # (b_j, w_stream), float32
        return rows[:, : rows.shape[1] // 2] if part == MEAN_HALF else rows  # (b_j, w)

    def close(self) -> None:
        self.view.close()
        if self.profile is not None:
            self.profile.close()


def open_probe_features(
    record: Mapping[str, Any], branch_specs: Sequence[str], sequences: Sequence[str], *, batch_size: int,
) -> IndexedBranchEmbeddings:
    """The cell's branches over `sequences`, verified once: a stored base's rows are all checked before this returns."""
    setting = validate_probe_features(record)
    specs = [parse_branch_spec(token) for token in branch_specs]
    branches = [branch_stream(spec) for spec in specs]
    if len(set(branches)) != len(branches):
        raise ValueError("a probe input needs distinct branches.")
    reads_profile = any(stream == PROFILE_STREAM for stream, _ in branches)
    canonical_streams = sorted({stream for stream, _ in branches if stream != PROFILE_STREAM})
    if reads_profile != (PROFILE_ROOT in setting):
        raise ValueError(f"a cell names {PROFILE_ROOT} exactly when a branch reads the Atlas profile; branches {list(branch_specs)}, setting {sorted(setting)}.")
    if not canonical_streams:
        raise ValueError("the Atlas profile joins at least one pooled stream of the base's canonical store; it is not read alone.")
    inventory = sequence_inventory(list(dict.fromkeys(sequences)))
    if setting["kind"] == GENERATED:
        if set(canonical_streams) != {FINAL_MEAN_VAR}:
            raise ValueError(f"the control {setting['control']} has no {SAE_MAX} stream; it reads the final mean and variance only.")
        view = MaterializedControl(SyntheticControlView(setting["control"], inventory, budget=GENERATED_BUDGET))
        block_rows = GENERATED_BUDGET.max_rows
    else:
        view = open_canonical_view(setting["root"], inventory, streams=canonical_streams, budget=STORED_BUDGET, persistent_reader=True)
        block_rows = None
    for spec, (stream, _) in zip(specs, branches, strict=True):
        if spec.sparse and view.descriptor(stream).width != parse_sae_model_name(spec.model_name).codebook_dim:
            raise ValueError(f"{spec.slug} names a codebook of {parse_sae_model_name(spec.model_name).codebook_dim} codes, but the store's {stream} has {view.descriptor(stream).width}.")
    # Every sequence's profile is checked here, before any training, so a protein `featurize` skipped stops the cell.
    profile = AtlasProfileFeature(setting[PROFILE_ROOT], list(inventory)) if reads_profile else None
    joined = IndexedBranchEmbeddings(ProbeBranchView(view, branches, block_rows, profile))
    if batch_size > joined.block_rows:
        raise ValueError(f"the probe batch of {batch_size} rows exceeds the {joined.block_rows} rows a read may return.")
    return joined


def probe_provenance(record: Mapping[str, Any], branch_specs: Sequence[str]) -> dict[str, Any]:
    """What a package read, for its `features.json`: the store and streams, or the control's arithmetic."""
    setting = validate_probe_features(record)
    streams = sorted({stream for stream in (branch_stream(parse_branch_spec(token))[0] for token in branch_specs) if stream != PROFILE_STREAM})
    if setting["kind"] == GENERATED:
        return {"kind": GENERATED, "base": setting["base"], "generator": SyntheticControlView(setting["control"], {}).identity}
    manifest = read_manifest(setting["root"])
    provenance = _canonical_provenance(setting, manifest, streams)
    if PROFILE_ROOT in setting:
        provenance["atlas_profile"] = profile_provenance(setting[PROFILE_ROOT])
    return provenance


def _canonical_provenance(setting: Mapping[str, Any], manifest: Mapping[str, Any], streams: Sequence[str]) -> dict[str, Any]:
    """The base's canonical store as a package records it: identity, crop, and each stream's key, width and descriptor digest."""
    return {
        "kind": STORED, "base": setting["base"], "store_base": manifest["base"], "store_schema": manifest["schema"],
        "special_tokens": manifest["special_tokens"], "row_layout": manifest["row_layout"], "max_residues": manifest["max_residues"],
        "model_state_sha256": manifest["model_state_sha256"], "random_init": manifest["random_init"], "hub_repo": manifest["hub_repo"],
        "streams": {name: {"key": manifest["streams"][name]["key"], "width": manifest["streams"][name]["width"],
                           "descriptor_sha256": manifest["streams"][name]["descriptor_sha256"]} for name in streams},
    }
