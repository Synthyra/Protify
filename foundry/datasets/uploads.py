"""Unchecked Hub uploads for build scripts: a `DatasetDict`, a folder, or an embeddings directory.

These commit and return. For a release whose bytes must be read back and compared after the commit,
use `publish_dataset` in `foundry.datasets.hub` instead.

Authentication belongs to `huggingface_hub`, which reads `HF_TOKEN` and then the token
`hf auth login` stored. Nothing here accepts, passes, or stores a token; `require_hub_token` only
stops a build before its first write when none resolves.
"""

from __future__ import annotations

import tempfile

from pathlib import Path
from typing import Protocol
from huggingface_hub import HfApi, get_token, upload_file


class HubDatasetDict(Protocol):
    """What `push_dataset_to_hub` uses of a `datasets.DatasetDict`, which foundry does not depend on."""

    def push_to_hub(self, repo_id: str, *, private: bool, max_shard_size: str) -> object: ...


def require_hub_token() -> None:
    """Stop before a Hub write when no token resolves."""
    if get_token() is None:
        raise SystemExit("Pushing to the Hub needs a token: run `hf auth login` once, or set HF_TOKEN.")


def push_dataset_to_hub(
    dataset_dict: HubDatasetDict,
    repo_id: str,
    private: bool = False,
    max_shard_size: str = "1GB",
    readme_content: str | None = None,
) -> None:
    """Push a `datasets.DatasetDict` to a dataset repository, then its README when one is given."""
    require_hub_token()
    dataset_dict.push_to_hub(repo_id, private=private, max_shard_size=max_shard_size)
    if readme_content:
        with tempfile.TemporaryDirectory() as scratch:
            readme_path = Path(scratch) / "README.md"
            readme_path.write_text(readme_content, encoding="utf-8")
            upload_file(
                path_or_fileobj=str(readme_path),
                repo_id=repo_id,
                repo_type="dataset",
                path_in_repo="README.md",
            )


def upload_folder_to_hub(
    folder_path: str,
    repo_id: str,
    repo_type: str = "dataset",
    private: bool = False,
    path_in_repo: str | None = None,
) -> None:
    """Upload a folder's contents in one commit, creating the repository if it is missing."""
    require_hub_token()
    api = HfApi()
    api.create_repo(repo_id, repo_type=repo_type, private=private, exist_ok=True)
    api.upload_folder(folder_path=folder_path, repo_id=repo_id, repo_type=repo_type, path_in_repo=path_in_repo)


def upload_embeddings_to_hf(output_dir: str, repo_id: str, private: bool = False) -> None:
    """Upload every `.pt` and `.json` file under `output_dir` to a dataset repository in one commit.

    The Hub's Xet storage deduplicates by chunk, so a re-upload after an incremental change
    transfers only the new chunks.
    """
    require_hub_token()
    api = HfApi()
    api.create_repo(repo_id, repo_type="dataset", private=private, exist_ok=True)
    api.upload_folder(
        folder_path=output_dir,
        repo_id=repo_id,
        repo_type="dataset",
        allow_patterns=["*.pt", "*.json"],
        commit_message="Update proteome embeddings",
    )
    print(f"Uploaded to https://huggingface.co/datasets/{repo_id}")


def build_basic_dataset_card(
    repo_id: str,
    split_sizes: dict[str, int],
    features_dict: dict[str, str],
    description: str = "",
    citation: str = "",
) -> str:
    """A dataset README whose front matter lists the features, the split sizes, and train, valid, and test files."""
    feature_lines = "\n".join(f"  - name: {name}\n    dtype: {dtype}" for name, dtype in features_dict.items())
    split_lines = "\n".join(f"  - name: {name}\n    num_examples: {count}" for name, count in split_sizes.items())
    yaml_block = (
        "---\n"
        "dataset_info:\n"
        "  features:\n"
        f"{feature_lines}\n"
        "  splits:\n"
        f"{split_lines}\n"
        "configs:\n"
        "- config_name: default\n"
        "  data_files:\n"
        "  - split: train\n    path: data/train-*\n"
        "  - split: valid\n    path: data/valid-*\n"
        "  - split: test\n    path: data/test-*\n"
        "---\n"
    )
    return f"""{yaml_block}

# {repo_id.split('/')[-1]}

{description}

## Citation

{citation}

Generated by `{repo_id}`.
"""


